export function optionLabel(lang: Lang, label: string): string {
  if (lang !== 'en') return label;
  const decade = label.match(/^(\d+)年代$/);
  if (decade)
    return `${decade[1].length === 2 ? '19' + decade[1] : decade[1]}s`;
  return OPTION_EN[label] || label;
}
